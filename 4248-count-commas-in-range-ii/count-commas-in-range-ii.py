class Solution(object):
    def countCommas(self,n):
        c=0
        if n>=1000:
            c+=min(n,999999)-999
        if n>=1000000:
            c+=(min(n,999999999)+1-1000000)*2
        if n>=1000000000:
            c+=(min(n,999999999999)+1-1000000000)*3
        if n>=1000000000000:
            c+=(min(n,999999999999999)+1-1000000000000)*4
        if n>=1000000000000000:
            c+=(n+1-1000000000000000)*5
        return c